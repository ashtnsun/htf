// Generates src/app/icon.svg (the favicon) from the T-rex pixel map.
// The map in src/components/brand/dino-pixels.ts is the one source for every dinosaur
// drawing on the site, so the favicon is generated from it rather than traced again:
// solid cells, no outlines, the eye carved as an empty cell. The canvas is transparent, so
// the dinosaur sits on whatever the browser paints behind a tab; anything that needs an
// opaque ground (apple-icon.tsx) paints it itself.
// Run: pnpm gen:icon   (no dependencies)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const mapFile = path.join(root, "src", "components", "brand", "dino-pixels.ts");
const outFile = path.join(root, "src", "app", "icon.svg");

const GREEN = "#03C652";
/** Empty cells around the map, squaring off the canvas; 1 unit per cell, so nothing is scaled. */
const PAD_X = 2;
const PAD_Y = 1;

const source = fs.readFileSync(mapFile, "utf8");
const block = source.match(/DINO_PIXELS:\s*readonly string\[\]\s*=\s*\[([\s\S]*?)\];/);
if (!block) throw new Error(`Could not find DINO_PIXELS in ${mapFile}`);
const rows = [...block[1].matchAll(/"([.#]+)"/g)].map((m) => m[1]);
if (rows.length === 0) throw new Error("DINO_PIXELS parsed as empty");

const cols = rows[0].length;
if (rows.some((row) => row.length !== cols)) throw new Error("DINO_PIXELS rows are ragged");

const width = cols + PAD_X * 2;
const height = rows.length + PAD_Y * 2;

/** One rect per horizontal run of filled cells, so the file stays small. */
const rects = [];
rows.forEach((row, y) => {
  for (const run of row.matchAll(/#+/g)) {
    rects.push(
      `<rect x="${run.index + PAD_X}" y="${y + PAD_Y}" width="${run[0].length}" height="1"/>`,
    );
  }
});

const svg =
  `<!-- Generated by pnpm gen:icon from src/components/brand/dino-pixels.ts. Do not hand-edit. -->` +
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" shape-rendering="crispEdges">` +
  `<g fill="${GREEN}">${rects.join("")}</g>` +
  `</svg>\n`;

fs.writeFileSync(outFile, svg);
console.log(
  `icon.svg: ${cols}x${rows.length} cells on a ${width}x${height} canvas, ${rects.length} rects`,
);
